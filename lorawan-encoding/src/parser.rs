//! Zero-copy parsing of LoRaWAN frames as borrowed views.
//!
//! This module replaced the earlier `T: AsRef<[u8]>` generic-over-storage
//! design:
//!
//! * Fixed-size wire fields ([`DevAddr`], [`DevEui`], [`JoinEui`],
//!   [`DevNonce`], [`JoinNonce`], [`NetId`], [`Frequency`]) become plain
//!   owned `[u8; N]` newtypes (`Copy`, `Eq`, `Hash`) with explicit
//!   wire-order/value conversions.
//! * Parsing produces zero-copy read-only views with all structural
//!   validation done once at the boundary, so every accessor afterwards is
//!   infallible by construction. One monomorphization regardless of where the
//!   bytes live.
//! * Decryption stays in place but takes the `&mut [u8]` explicitly, keeping
//!   the encrypted/decrypted typestate without any storage generic.
//! * MAC command parsing ([`crate::maccommands`], [`crate::certification`],
//!   [`crate::multicast`]) yields `Result` per command instead of silently
//!   stopping at malformed input,
//!   with the framing generated by the `CommandHandler` derive from the
//!   enums' `#[cmd]` attributes.
//! * Frames are built from plain structs ([`DataFrame`], [`JoinRequest`],
//!   [`JoinAccept`]) with `build_into(&mut buf)`; the types make most
//!   invalid frames unrepresentable.
//! * One [`Error`] enum implementing `Display` and `core::error::Error`.
//!
//! Deliberate divergences from the retired design, for anyone migrating:
//!
//! * `f_port()` returns `Some` when an FPort byte is present with an empty
//!   FRMPayload. The old code reported `None` in that case, conflating
//!   "FPort absent" with "FPort present, payload empty".
//! * Wire fields are explicit about byte order: the wire transmits them
//!   little-endian, so `from_value`/`value` convert accordingly. The old
//!   `From<u32> for DevAddr` and `From<u16> for DevNonce` used big-endian
//!   array order, which round-tripped through the wire with flipped
//!   endianness.
//! * All parse entry points reject frames with a non-R1 major version; the
//!   old `EncryptedDataPayload::new` accepted them.
//! * A MAC command stream with a malformed tail yields `Err`; the old
//!   iterator ended silently.
//!
//! # Examples
//!
//! Receiving on a device: inspect the frame read-only, look up the session
//! by [`DevAddr`], verify the MIC, then decrypt in place.
//!
//! ```
//! use lorawan::default_crypto::DefaultCrypto;
//! use lorawan::keys::{AppSKey, NwkSKey};
//! use lorawan::parser::{DecryptedDataPayload, DevAddr, EncryptedDataPayload, FrmPayload};
//!
//! let mut buf = [
//!     0x40, 0x04, 0x03, 0x02, 0x01, 0x80, 0x01, 0x00, 0x01, 0xa6, 0x94, 0x64, 0x26, 0x15,
//!     0xd6, 0xc3, 0xb5, 0x82,
//! ];
//! let nwk_crypto = DefaultCrypto::new(NwkSKey::from([2; 16]).inner());
//! let app_crypto = DefaultCrypto::new(AppSKey::from([1; 16]).inner());
//!
//! let phy = EncryptedDataPayload::parse(&buf).unwrap();
//! assert_eq!(phy.fhdr().dev_addr(), DevAddr::from_value(0x01020304));
//! assert!(phy.validate_mic(&nwk_crypto, 1));
//!
//! let decrypted =
//!     DecryptedDataPayload::decrypt_in_place(&mut buf, Some(&nwk_crypto), Some(&app_crypto), 1)
//!         .unwrap();
//! assert_eq!(decrypted.frm_payload(), FrmPayload::Data(b"hello"));
//! ```
//!
//! Sending: describe the frame with a struct literal and build it into a
//! caller-provided buffer.
//!
//! ```
//! use core::num::NonZeroU8;
//! use lorawan::default_crypto::DefaultCrypto;
//! use lorawan::keys::{AppSKey, NwkSKey};
//! use lorawan::creator::{DataFrame, Payload};
//! use lorawan::parser::{DataFrameType, DevAddr};
//!
//! let frame = DataFrame {
//!     frame_type: DataFrameType::ConfirmedUp,
//!     dev_addr: DevAddr::from_value(0x01020304),
//!     adr: true,
//!     fcnt: 42,
//!     payload: Payload::Data { f_port: NonZeroU8::new(1).unwrap(), data: b"hello" },
//!     ..Default::default()
//! };
//! let mut buf = [0u8; 64];
//! let nwk_crypto = DefaultCrypto::new(NwkSKey::from([2; 16]).inner());
//! let app_crypto = DefaultCrypto::new(AppSKey::from([1; 16]).inner());
//! let bytes = frame.build_into(&mut buf, &nwk_crypto, Some(&app_crypto)).unwrap();
//! assert_eq!(bytes.len(), 18);
//! ```

